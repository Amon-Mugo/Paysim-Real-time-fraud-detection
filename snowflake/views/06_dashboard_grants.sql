-- Dashboard read-only access.
-- Creates FRAUD_DASHBOARD_READER with SELECT on the five M9 views only.
-- Base tables stay hidden; the views execute with their owner's privileges.
-- Run as ACCOUNTADMIN, after files 01 to 05.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FRAUD_DASHBOARD_READER;

GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_DASHBOARD_READER;
GRANT USAGE ON DATABASE FRAUD_DETECTION TO ROLE FRAUD_DASHBOARD_READER;
GRANT USAGE ON SCHEMA FRAUD_DETECTION.MONITORING TO ROLE FRAUD_DASHBOARD_READER;

GRANT SELECT ON VIEW FRAUD_DETECTION.MONITORING.V_ALERT_INCIDENTS TO ROLE FRAUD_DASHBOARD_READER;
GRANT SELECT ON VIEW FRAUD_DETECTION.MONITORING.V_ALERTS_FEED TO ROLE FRAUD_DASHBOARD_READER;
GRANT SELECT ON VIEW FRAUD_DETECTION.MONITORING.V_TRANSACTIONS_SCORED TO ROLE FRAUD_DASHBOARD_READER;
GRANT SELECT ON VIEW FRAUD_DETECTION.MONITORING.V_ALERT_SUMMARY_HOURLY TO ROLE FRAUD_DASHBOARD_READER;
GRANT SELECT ON VIEW FRAUD_DETECTION.MONITORING.V_ACCOUNT_RISK TO ROLE FRAUD_DASHBOARD_READER;