-- used in setting up the snowflake account settings and configurations and roles
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS FRAUD_WH
    WAREHOUSE_SIZE   = XSMALL
    AUTO_SUSPEND     = 60 
    AUTO_RESUME      = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS FRAUD_DETECTION;
CREATE SCHEMA IF NOT EXISTS FRAUD_DETECTION.MONITORING;

USE WAREHOUSE FRAUD_WH;
USE SCHEMA FRAUD_DETECTION.MONITORING;

--  serving table used for dashbourd configs
CREATE TRANSIENT TABLE IF NOT EXISTS TRANSACTIONS_RECENT (
    TRANSACTION_ID    STRING,
    EVENT_TIME        TIMESTAMP_NTZ,
    TRANSACTION_TYPE  STRING,
    AMOUNT            DOUBLE,
    NAME_ORIG         STRING,
    OLD_BALANCE_ORIG  DOUBLE,
    NEW_BALANCE_ORIG  DOUBLE,
    NAME_DEST         STRING,
    OLD_BALANCE_DEST  DOUBLE,
    NEW_BALANCE_DEST  DOUBLE,
    LATITUDE          DOUBLE,
    LONGITUDE         DOUBLE,
    KAFKA_PARTITION   NUMBER(10, 0),
    KAFKA_OFFSET      NUMBER(19, 0),
    KAFKA_TIMESTAMP   TIMESTAMP_NTZ,
    FRAUD_SCORE       DOUBLE,
    MODEL_VERSION     STRING,
    INGESTED_AT       TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TRANSIENT TABLE IF NOT EXISTS ALERTS (
    ALERT_ID         STRING,
    RULE_NAME        STRING,
    NAME_ORIG        STRING,
    ALERT_TIME       TIMESTAMP_NTZ,
    TRANSACTION_IDS  ARRAY,
    DETAILS          VARIANT,
    INGESTED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- STAGING USED FOR DATA INCOMING FROM SPARK MICRO BATCHES
CREATE TRANSIENT TABLE IF NOT EXISTS STG_TRANSACTIONS_RECENT (
    TRANSACTION_ID    STRING,
    EVENT_TIME        TIMESTAMP_NTZ,
    TRANSACTION_TYPE  STRING,
    AMOUNT            DOUBLE,
    NAME_ORIG         STRING,
    OLD_BALANCE_ORIG  DOUBLE,
    NEW_BALANCE_ORIG  DOUBLE,
    NAME_DEST         STRING,
    OLD_BALANCE_DEST  DOUBLE,
    NEW_BALANCE_DEST  DOUBLE,
    LATITUDE          DOUBLE,
    LONGITUDE         DOUBLE,
    KAFKA_PARTITION   NUMBER(10, 0),
    KAFKA_OFFSET      NUMBER(19, 0),
    KAFKA_TIMESTAMP   TIMESTAMP_NTZ,
    FRAUD_SCORE       DOUBLE,
    MODEL_VERSION     STRING
);

CREATE TRANSIENT TABLE IF NOT EXISTS STG_ALERTS_STRUCTURING (
    ALERT_ID         STRING,
    RULE_NAME        STRING,
    NAME_ORIG        STRING,
    ALERT_TIME       TIMESTAMP_NTZ,
    TRANSACTION_IDS  STRING,
    DETAILS          STRING
);
CREATE TRANSIENT TABLE IF NOT EXISTS STG_ALERTS_VELOCITY LIKE STG_ALERTS_STRUCTURING;
CREATE TRANSIENT TABLE IF NOT EXISTS STG_ALERTS_GEO LIKE STG_ALERTS_STRUCTURING;
CREATE TRANSIENT TABLE IF NOT EXISTS STG_ALERTS_ML LIKE STG_ALERTS_STRUCTURING;

--WRITE ROLES GOING TO BE USED 
CREATE ROLE IF NOT EXISTS FRAUD_WRITER;
GRANT USAGE ON DATABASE FRAUD_DETECTION TO ROLE FRAUD_WRITER;
GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_WRITER;
GRANT USAGE ON SCHEMA FRAUD_DETECTION.MONITORING TO ROLE FRAUD_WRITER;
GRANT CREATE STAGE ON SCHEMA FRAUD_DETECTION.MONITORING TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT ON TABLE TRANSACTIONS_RECENT TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT ON TABLE ALERTS TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT, TRUNCATE ON TABLE STG_TRANSACTIONS_RECENT TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT, TRUNCATE ON TABLE STG_ALERTS_STRUCTURING TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT, TRUNCATE ON TABLE STG_ALERTS_VELOCITY TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT, TRUNCATE ON TABLE STG_ALERTS_GEO TO ROLE FRAUD_WRITER;
GRANT SELECT, INSERT, TRUNCATE ON TABLE STG_ALERTS_ML TO ROLE FRAUD_WRITER;

CREATE OR REPLACE TASK PURGE_OLD_TRANSACTIONS 
   WAREHOUSE    = FRAUD_WH
   SCHEDULE     = 'USING CRON 0 3 * * * UTC'
AS
   DELETE FROM TRANSACTIONS_RECENT
   WHERE INGESTED_AT < DATEADD(day, -7, CURRENT_TIMESTAMP());

ALTER TASK PURGE_OLD_TRANSACTIONS RESUME;

-- SERVICE USER FOR THE SPARK WRITER (KEY-PAIR LOGIN ONLY)
CREATE USER IF NOT EXISTS FRAUD_WRITER_SVC
    TYPE              = SERVICE
    DEFAULT_ROLE      = FRAUD_WRITER
    DEFAULT_WAREHOUSE = FRAUD_WH
    DEFAULT_NAMESPACE = FRAUD_DETECTION.MONITORING;

ALTER USER FRAUD_WRITER_SVC SET RSA_PUBLIC_KEY = '<PUBLIC_KEY_BODY>';

GRANT ROLE FRAUD_WRITER TO USER FRAUD_WRITER_SVC;
